"""Read-only, independent DD/FTD verification for Miner market-signal views.

Never claims to reproduce proprietary IBD market calls. Prices come from Yahoo,
volumes from Npay index-series rows checked for date/close agreement by miner_volume.
No score or trading decision is generated by this module.
"""
from __future__ import annotations

from datetime import datetime
from zoneinfo import ZoneInfo
import numpy as np
import pandas as pd

from miner_dd_audit import calculate_dd_audit
from miner_ftd_audit import replay_ftd

KST = ZoneInfo('Asia/Seoul')
MIN_CONSECUTIVE = 80


def _day(value):
    return None if value is None else pd.Timestamp(value).strftime('%Y-%m-%d')


def assess_market_signal(frame, live_state_fn, *, now=None):
    """Check recent source coverage and independently replay the current market engine.

    Returns an explicit `verified` or `withheld` result; does not fabricate an
    FTD when none is active. Includes audit tables solely for optional UI detail.
    """
    answer = dict(status='withheld', reason='', source='', date='', matched=None,
                  dd_count=None, dd_dates=[], ftd=None, day1=None,
                  market_status='판정 보류', consecutive=0, dd_table=None,
                  ftd_events=None, ftd_checks=None)
    def hold(reason):
        answer['reason'] = reason
        return answer

    if frame is None or not isinstance(frame, pd.DataFrame):
        return hold('지수 일봉 자료가 없습니다')
    if not {'Close', 'Low', 'Volume'}.issubset(frame.columns) or len(frame)<MIN_CONSECUTIVE:
        return hold('가격·저가·거래량 80거래일 미만')
    if not isinstance(frame.index,pd.DatetimeIndex) or frame.index.has_duplicates or not frame.index.is_monotonic_increasing:
        return hold('지수 거래일 중복·역순')
    lastdate=frame.index[-1]
    answer['date']=_day(lastdate)
    clock=(now or datetime.now(KST)).date()
    lag=(clock-lastdate.date()).days
    if lag<0 or lag>7:
        return hold(f'지수 기준일 지연/미래 날짜: {answer["date"]}')

    source=str(frame.attrs.get('index_volume_source') or '')
    matched=frame.attrs.get('index_volume_matched')
    answer['source']=source or '출처 정보 없음'
    answer['matched']=matched
    # Source guarantee is an important input assertion, not merely a nonzero-volume test.
    if not source.startswith('네이버 지수') or type(matched) is not int or matched<MIN_CONSECUTIVE:
        return hold('네이버 지수 거래량의 날짜·종가 대조 및 80일 확보가 확인되지 않음')
    recent=frame[['Close','Low','Volume']].tail(MIN_CONSECUTIVE).apply(pd.to_numeric,errors='coerce')
    if recent.isna().any().any() or not np.isfinite(recent.to_numpy(dtype=float)).all() or not (recent>0).all().all():
        return hold('최근 80거래일에 NaN·0·비정상 가격/거래량 존재')
    answer['consecutive']=MIN_CONSECUTIVE
    if (recent.index[-1]-recent.index[0]).days>155:
        return hold('최근 80개 관측일의 달력 간격이 너무 큼')

    # The DD condition reproduces the explicit *numeric* engine rule independently:
    # -0.2% daily close, higher volume; expiration at 25 sessions or +5% recovery.
    arr=frame[['Close','Volume']].apply(pd.to_numeric,errors='coerce')
    close=arr['Close'].to_numpy(dtype=float)
    volume=arr['Volume'].to_numpy(dtype=float)
    n=len(arr)
    expected_dd=[]
    for i in range(max(1,n-25),n):
        if not all(np.isfinite(v) and v>0 for v in (close[i],close[i-1],volume[i],volume[i-1])):
            return hold('DD 최근 25거래일 주변 가격·거래량 누락')
        if close[i]<=close[i-1]*0.998 and volume[i]>volume[i-1]:
            following=close[i+1:n]
            if not np.isfinite(following).all():
                return hold('DD 반등 소멸 확인에 필요한 종가 누락')
            if not (following>=close[i]*1.05).any():
                expected_dd.append(_day(frame.index[i]))
    dd_table=calculate_dd_audit(frame,lookback=60)
    table_dates=set(dd_table.loc[dd_table['판정']=='유효 DD','날짜'].tolist()) if not dd_table.empty else set()
    if table_dates!=set(expected_dd):
        return hold('DD 날짜별 감사표와 25일·5% 회복 재계산 불일치')

    replay=replay_ftd(frame)
    if replay['status']=='판정 보류':
        return hold('FTD 독립 재계산 보류: '+str(replay.get('reason') or '거래량 자료 부족'))
    try:
        live=live_state_fn(frame)
        if live.get('status')=='판정 보류':
            return hold('실제 DD·FTD 엔진 판정 보류: '+str(live.get('reason','')))
        livedd=[_day(d) for d in live.get('dd',[])]
        liveftd=_day(live.get('ftd'))
        liveday1=_day(live.get('day1'))
        refday1=_day(replay['day1'])
        refftd=_day(replay['ftd'])
    except (ValueError,KeyError,TypeError,IndexError,AttributeError) as e:
        return hold(f'실제 엔진 응답 형식 오류: {type(e).__name__}')
    if sorted(livedd)!=sorted(expected_dd):
        return hold('화면 유효 DD 발생 날짜와 독립 계산 날짜 불일치')
    if (live['status']!=replay['status'] or liveday1!=refday1
        or liveftd!=refftd or len(expected_dd)!=replay['dd_count']):
        return hold('FTD 상태·Day1·FTD 날짜 또는 DD 수치가 독립 재생과 불일치')
    answer.update(status='verified', reason='검증된 최근 거래량과 두 독립 산식이 일치',
                  dd_count=len(expected_dd),dd_dates=sorted(expected_dd,reverse=True),
                  ftd=liveftd,day1=liveday1,market_status=str(live['status']),
                  dd_table=dd_table,ftd_events=replay['events'],ftd_checks=replay['checks'])
    return answer


def render_quality_detail(datasets, live_state_fn):
    """Readable, deliberately collapsible independent evidence panel."""
    import streamlit as st
    with st.expander('🔎 DD·FTD 독립검산 · 거래량 출처·발생/소멸·Day 1',expanded=False):
        st.caption('최근 연속 80거래일 지수 거래량 확인 · 같은 날짜 지수 종가 대조 · DD 25거래일/5% 소멸 · FTD 4일차 이후 1%/거래량 증가. IBD 공식 판정이 아닌 광부 자체 규칙 검증입니다.')
        for name in ('KOSPI','KOSDAQ'):
            if name not in datasets:
                st.warning(f'{name}: 지수 자료 없음');continue
            a=assess_market_signal(datasets[name],live_state_fn)
            st.markdown(f'**{name}** · 지수 기준 {a["date"] or "미확인"}')
            if a['status']!='verified':
                st.warning(f'원인 확인 전 DD·FTD 확정 보류: {a["reason"]}')
            else:
                st.success(f'DD {a["dd_count"]}회 / FTD {a["ftd"] or "유효 없음"} / 시장 상태 {a["market_status"]} · 엔진·독립 검산 일치')
                st.caption(f'발생·미소멸 DD 날짜: {", ".join(a["dd_dates"]) if a["dd_dates"] else "없음"}')
                if a['dd_table'] is not None and not a['dd_table'].empty:
                    st.dataframe(a['dd_table'],hide_index=True,use_container_width=True)
                if a['ftd_checks'] is not None and not a['ftd_checks'].empty:
                    st.caption('FTD 발생·실패·대기 근거 (최근 30개)')
                    st.dataframe(a['ftd_checks'].tail(30).sort_values('날짜',ascending=False),hide_index=True,use_container_width=True)
            st.caption(f'거래량 공급처: {a["source"]} · 날짜/종가 매칭 {a["matched"] if a["matched"] is not None else "미확인"}회 · KRX 독립 검증 아님')
